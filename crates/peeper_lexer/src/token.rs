/// Every operator and punctuation token by its text, longest first within each
/// leading character, so the lexer's first match is the right one.
pub const OPERATORS: &[(&str, TokenKind)] = {
    use TokenKind::*;
    &[
        ("::", ColonColon),
        (":", Colon),
        ("==", EqualEqual),
        ("=>", FatArrow),
        ("=", Assign),
        ("!=", BangEqual),
        ("!!", BangBang),
        ("!", Bang),
        ("<=", LessEqual),
        ("<<", ShiftLeft),
        ("<", Less),
        (">=", GreaterEqual),
        (">>", ShiftRight),
        (">", Greater),
        ("&&", AndAnd),
        ("&", Amp),
        ("||", OrOr),
        ("|>", PipeArrow),
        ("|", Bar),
        ("??", QuestionQuestion),
        ("?", Question),
        ("->", Arrow),
        ("--", MinusMinus),
        ("-=", MinusAssign),
        ("-", Minus),
        ("++", PlusPlus),
        ("+=", PlusAssign),
        ("+", Plus),
        ("*=", StarAssign),
        ("*", Asterisk),
        ("/=", SlashAssign),
        ("/", Slash),
        ("%=", PercentAssign),
        ("%", Percent),
        ("...", Ellipsis),
        ("..=", DotDotEq),
        ("..", DotDot),
        (".", Dot),
        ("@", At),
        ("^", Caret),
        ("~", Tilde),
        (",", Comma),
        ("#", Hash),
        (";", Semicolon),
        ("(", LeftParen),
        (")", RightParen),
        ("{", LeftBrace),
        ("}", RightBrace),
        ("[", LeftBracket),
        ("]", RightBracket),
    ]
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spellings_agree_with_keywords_and_operators() {
        for &(text, kind) in OPERATORS {
            assert_eq!(kind.spelling(), Some(text));
        }
        for text in ["fn", "let", "orelse", "rawptr", "unsafe"] {
            let kind = keyword(text).unwrap();
            assert_eq!(kind.spelling(), Some(text));
        }
        assert_eq!(keyword("name"), None);
        assert_eq!(TokenKind::Fn.name(), "function");
        assert_eq!(TokenKind::Ident.spelling(), None);
    }
}
