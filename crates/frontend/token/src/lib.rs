//! The tokens the lexer produces.

use source::Span;

/// One token: its kind and where its text is. The text itself is the file's
/// text at `span`; literal values are decoded later.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)] // parser tables are indexed by kind
pub enum TokenKind {
    // Named kinds: their text varies, so `text` describes them.
    Eof,
    Ident,
    Number,
    String,
    CString,
    Char,
    ByteChar,
    DocComment,
    // Operators and punctuation.
    Assign,
    Plus,
    Minus,
    Asterisk,
    Slash,
    Percent,
    PlusAssign,
    MinusAssign,
    StarAssign,
    SlashAssign,
    PercentAssign,
    PlusPlus,
    MinusMinus,
    Bang,
    Question,
    At,
    Amp,
    Caret,
    Tilde,
    Less,
    Greater,
    ShiftLeft,
    ShiftRight,
    EqualEqual,
    BangEqual,
    LessEqual,
    GreaterEqual,
    AndAnd,
    OrOr,
    Bar,
    PipeArrow,
    QuestionQuestion,
    BangBang,
    FatArrow,
    Arrow,
    Colon,
    ColonColon,
    Comma,
    Dot,
    DotDot,
    DotDotEq,
    Ellipsis,
    Hash,
    Semicolon,
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    // Keywords.
    Import,
    Const,
    Type,
    Struct,
    Iface,
    Enum,
    Fn,
    Let,
    If,
    Else,
    Match,
    For,
    Break,
    Continue,
    Return,
    From,
    Free,
    Print,
    Println,
    Rawptr,
    As,
    Is,
    In,
    With,
    Mut,
    Orelse,
    None,
    True,
    False,
}

