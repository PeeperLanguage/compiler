// Command gen reads the node structs in ../nodes.go and writes ../nodes_gen.go:
// for each struct a reader (Tree.X) and a packer (Tree.PackX), and
// Tree.Children. These are the only code that turns a child into a slot or an
// Extra position, so no index is written by hand.
//
// Run it with: go generate ./internal/frontend/ast
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"reflect"
	"strconv"
	"strings"
)

// A node is one struct of nodes.go and the kinds it describes.
type node struct {
	name     string
	kinds    []string
	children []child
}

// A child is one field of a node struct.
type child struct {
	name   string
	list   bool   // the field is a List
	place  string // "A", "B" or "" for Extra
	offset int    // the position in Extra after the node's B slot, when place is ""
}

// slot is the Go expression that reads c from the node n, as an Index.
func (c child) slot() string {
	switch {
	case c.place == "A":
		return "n.A"
	case c.place == "B":
		return "n.B"
	case c.offset == 0:
		return "t.Extra[n.B]"
	}
	return fmt.Sprintf("t.Extra[n.B+%d]", c.offset)
}

// typed converts the Index expression e to the type of c.
func (c child) typed(e string) string {
	if c.list {
		return "List(" + e + ")"
	}
	return e
}

// index converts the field expression e of type c to an Index.
func (c child) index(e string) string {
	if c.list {
		return "Index(" + e + ")"
	}
	return e
}

// read parses the node structs of file.
func read(file string) []node {
	f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	var nodes []node
	owner := map[string]string{} // the struct of each kind named in a directive
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE || gen.Doc == nil {
			continue
		}
		var kinds []string
		for _, comment := range gen.Doc.List {
			if rest, ok := strings.CutPrefix(comment.Text, "//ast:node "); ok {
				kinds = strings.Fields(rest)
			}
		}
		if kinds == nil {
			continue
		}
		spec := gen.Specs[0].(*ast.TypeSpec)
		n := node{name: spec.Name.Name, kinds: kinds}
		for _, kind := range kinds {
			if other, ok := owner[kind]; ok {
				log.Fatalf("%s is named by both %s and %s", kind, other, n.name)
			}
			owner[kind] = n.name
		}
		extra := 0
		for _, field := range spec.Type.(*ast.StructType).Fields.List {
			if len(field.Names) == 0 {
				log.Fatalf("%s: an embedded field is not a child", n.name)
			}
			typ, ok := field.Type.(*ast.Ident)
			if !ok || typ.Name != "Index" && typ.Name != "List" {
				log.Fatalf("%s: a child is an Index or a List", n.name)
			}
			place := ""
			if field.Tag != nil {
				tag, _ := strconv.Unquote(field.Tag.Value)
				place = reflect.StructTag(tag).Get("ast")
			}
			// A field may declare several names (a, b Index); each is a child.
			for _, name := range field.Names {
				c := child{name: name.Name, list: typ.Name == "List", place: place}
				switch c.place {
				case "A", "B":
				case "":
					c.offset = extra
					extra++
				default:
					log.Fatalf("%s.%s: ast tag must be A or B", n.name, c.name)
				}
				n.children = append(n.children, c)
			}
		}
		if extra > 0 {
			for _, c := range n.children {
				if c.place == "B" {
					log.Fatalf("%s: B holds where the Extra children start; %s cannot be kept there", n.name, c.name)
				}
			}
		}
		nodes = append(nodes, n)
	}
	return nodes
}

func generate(nodes []node) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen/main.go from nodes.go; DO NOT EDIT.\n\npackage ast\n\nimport \"iter\"\n")

	for _, n := range nodes {
		var reads, packs []string
		a, bSlot := "None", "None"
		for _, c := range n.children {
			reads = append(reads, c.name+": "+c.typed(c.slot()))
			switch c.place {
			case "A":
				a = c.index("v." + c.name)
			case "B":
				bSlot = c.index("v." + c.name)
			default:
				packs = append(packs, c.index("v."+c.name))
			}
		}
		fmt.Fprintf(&b, "\n// %s returns the children of node i, a %s.\n", n.name, strings.Join(n.kinds, " or "))
		fmt.Fprintf(&b, "func (t *Tree) %s(i Index) %s {\n\tn := t.Nodes[i]\n", n.name, n.name)
		fmt.Fprintf(&b, "\treturn %s{%s}\n}\n", n.name, strings.Join(reads, ", "))
		fmt.Fprintf(&b, "\n// Pack%s keeps the children v in the tree and returns the slots of their node.\n", n.name)
		if len(packs) == 0 {
			fmt.Fprintf(&b, "func (*Tree) Pack%s(v %s) Slots {\n\treturn Slots{A: %s, B: %s}\n}\n", n.name, n.name, a, bSlot)
			continue
		}
		fmt.Fprintf(&b, "func (t *Tree) Pack%s(v %s) Slots {\n\tb := Index(len(t.Extra))\n", n.name, n.name)
		fmt.Fprintf(&b, "\tt.Extra = append(t.Extra, %s)\n\treturn Slots{A: %s, B: b}\n}\n", strings.Join(packs, ", "), a)
	}

	b.WriteString(`
// Children returns the children of node i in source order, the items of its
// lists in place.
func (t *Tree) Children(i Index) iter.Seq[Index] {
	return func(yield func(Index) bool) {
		stopped := false
		node := func(child Index) {
			if !stopped && child != None {
				stopped = !yield(child)
			}
		}
		list := func(l List) {
			for _, child := range t.List(l) {
				node(child)
			}
		}
		n := t.Nodes[i]
		switch n.Kind {
`)
	for _, n := range nodes {
		fmt.Fprintf(&b, "\t\tcase %s:\n", strings.Join(n.kinds, ", "))
		for _, c := range n.children {
			if c.list {
				fmt.Fprintf(&b, "\t\t\tlist(List(%s))\n", c.slot())
			} else {
				fmt.Fprintf(&b, "\t\t\tnode(%s)\n", c.slot())
			}
		}
	}
	b.WriteString("\t\t}\n\t}\n}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, b.Bytes())
	}
	return out
}

func main() {
	if err := os.WriteFile("nodes_gen.go", generate(read("nodes.go")), 0o644); err != nil {
		log.Fatal(err)
	}
}
